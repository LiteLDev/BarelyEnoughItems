#!/usr/bin/env python3
"""Generate src/core/search/PinyinTable.cpp from mozillazg/pinyin-data.

Data source: https://github.com/mozillazg/pinyin-data
License of the data: MIT License, Copyright (c) 2016 mozillazg.

Download `kMandarin.txt` and `pinyin.txt` from that repository into a directory and run:

    python -I tools/pinyin/gen_pinyin_table.py <dir-with-txt-files> src/core/search/PinyinTable.cpp

Only the Python standard library is used. Tones are stripped and u-umlaut is written as `v`
(the usual IME convention, e.g. 绿 -> "lv"). For every ideograph in U+3400-U+4DBF and
U+4E00-U+9FFF the primary reading comes from kMandarin.txt (falling back to the first reading of
pinyin.txt); up to MAX_EXTRA further distinct toneless readings from pinyin.txt are kept as
polyphones.
"""

import re
import sys
import unicodedata
from pathlib import Path

RANGES = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF)]
MAX_EXTRA = 2
LINE_RE = re.compile(r"^U\+([0-9A-F]+):\s*([^#]+?)\s*(#.*)?$")


def toneless(reading: str) -> str:
    out = []
    for ch in unicodedata.normalize("NFD", reading.strip().lower()):
        if ch == "̈":  # combining diaeresis: u + diaeresis -> v
            if out and out[-1] == "u":
                out[-1] = "v"
            continue
        if unicodedata.combining(ch):
            continue
        out.append(ch)
    s = "".join(out)
    return s if s.isascii() and s.isalpha() else ""


def load(path: Path) -> dict:
    table = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = LINE_RE.match(line)
        if not m:
            continue
        cp = int(m.group(1), 16)
        readings = []
        for r in m.group(2).split(","):
            t = toneless(r)
            if t and t not in readings:
                readings.append(t)
        if readings:
            table[cp] = readings
    return table


def in_ranges(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in RANGES)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src = Path(sys.argv[1])
    mandarin = load(src / "kMandarin.txt")
    full = load(src / "pinyin.txt")

    readings = {}
    for cp in sorted(set(mandarin) | set(full)):
        if not in_ranges(cp):
            continue
        rs = []
        for r in mandarin.get(cp, [])[:1] + full.get(cp, []):
            if r not in rs:
                rs.append(r)
        # Polyphones only for the URO block; Extension A ideographs are rare in item names.
        readings[cp] = rs[: 1 + MAX_EXTRA] if cp >= 0x4E00 else rs[:1]

    syllables = sorted({r for rs in readings.values() for r in rs})
    index = {s: i + 1 for i, s in enumerate(syllables)}  # 0 = no reading
    assert len(syllables) < 1024

    out = []
    out.append("// GENERATED by tools/pinyin/gen_pinyin_table.py - do not edit by hand.")
    out.append("//")
    out.append("// Pinyin readings for CJK Unified Ideographs (U+3400-U+4DBF, U+4E00-U+9FFF).")
    out.append("// Data: mozillazg/pinyin-data (https://github.com/mozillazg/pinyin-data),")
    out.append("// MIT License, Copyright (c) 2016 mozillazg. Tones stripped, u-umlaut written as 'v'.")
    out.append("// clang-format off")
    out.append('#include "core/search/Pinyin.h"')
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("#include <string_view>")
    out.append("")
    out.append("namespace bei::core::pinyin::data {")
    out.append("")
    out.append(f"extern std::string_view const kSyllables[{len(syllables) + 1}];")
    out.append(f"std::string_view const kSyllables[{len(syllables) + 1}] = {{")
    line = '    "",'
    for s in syllables:
        item = f' "{s}",'
        if len(line) + len(item) > 118:
            out.append(line)
            line = "   "
        line += item
    out.append(line)
    out.append("};")
    out.append(f"extern std::size_t const kSyllableCount;")
    out.append(f"std::size_t const kSyllableCount = {len(syllables) + 1};")
    out.append("")

    for lo, hi in RANGES:
        name = f"kPrimary{lo:04X}"
        out.append(f"extern std::uint16_t const {name}[{hi - lo + 1}];")
        out.append(f"std::uint16_t const {name}[{hi - lo + 1}] = {{")
        vals = [index[readings[cp][0]] if cp in readings else 0 for cp in range(lo, hi + 1)]
        for i in range(0, len(vals), 28):
            out.append(",".join(str(v) for v in vals[i : i + 28]) + ",")
        out.append("};")
        out.append("")

    extra = []
    for cp, rs in readings.items():
        for r in rs[1:]:
            extra.append((cp << 10) | index[r])
    extra.sort()
    out.append("// (codepoint << 10) | syllable index, sorted.")
    out.append(f"extern std::uint32_t const kExtra[{len(extra)}];")
    out.append(f"std::uint32_t const kExtra[{len(extra)}] = {{")
    for i in range(0, len(extra), 14):
        out.append(",".join(f"0x{v:X}" for v in extra[i : i + 14]) + ",")
    out.append("};")
    out.append(f"extern std::size_t const kExtraCount;")
    out.append(f"std::size_t const kExtraCount = {len(extra)};")
    out.append("")
    out.append("} // namespace bei::core::pinyin::data")
    out.append("")

    Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(readings)} ideographs, {len(syllables)} syllables, {len(extra)} extra readings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
